// Prevents an extra console window on Windows in release builds.
#![cfg_attr(not(debug_assertions), windows_subsystem = "windows")]

mod connected_sources;
use connected_sources::{
    connected_source_delete_credential, connected_source_fetch, connected_source_get_credential,
    connected_source_set_credential,
};

// Tracker: Connected Sources (Phase 1) risk-reduction spike. A trivial,
// no-op command to settle -- cheaply, before any real reqwest/keyring
// logic is built on top of it -- whether an ad-hoc #[tauri::command]
// registered directly on the app's own Builder (not part of any plugin)
// needs a new capabilities/default.json entry at all, or whether the
// existing core:default permission already covers it. Plain commands
// like this are invoked by their bare name (no `plugin:` prefix -- that
// prefix is specific to plugin-exposed commands, generated by a plugin's
// own Builder machinery): window.__TAURI__.core.invoke('connected_source_ping').
#[tauri::command]
fn connected_source_ping() -> String {
    "ok".into()
}

fn main() {
    tauri::Builder::default()
        .plugin(tauri_plugin_opener::init())
        .plugin(tauri_plugin_notification::init())
        .plugin(tauri_plugin_updater::Builder::new().build())
        .plugin(tauri_plugin_process::init())
        .invoke_handler(tauri::generate_handler![
            connected_source_ping,
            connected_source_fetch,
            connected_source_set_credential,
            connected_source_get_credential,
            connected_source_delete_credential
        ])
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}
